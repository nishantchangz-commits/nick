def make_transaction(amount, txn_type, name, vpa, note):
    if txn_type == "credit":
        return UPITransaction(amount=amount, txn_type=TransactionType.CREDIT,
                               payer_name=name, vpa=vpa, note=note)
    return UPITransaction(amount=amount, txn_type=TransactionType.DEBIT,
                           payee_name=name, vpa=vpa, note=note)


def run_interactive(engine, lang, play):
    print("Interactive mode. Press Ctrl+C to quit.\n")
    while True:
        try:
            amount = float(input("Amount (INR): ").strip())
            txn_type = input("Type [credit/debit] (default credit): ").strip().lower() or "credit"
            name = input("Other party name: ").strip() or "Unknown"
            vpa = input("VPA (optional): ").strip()
            txn = make_transaction(amount, txn_type, name, vpa, "")
            announce_transaction(txn, engine=engine, language=lang, play=play)
            print()
        except KeyboardInterrupt:
            print("\nGoodbye!")
            break
        except ValueError as exc:
            print(f"Invalid input: {exc}\n")


def run_demo(engine, lang, play):
    print("Running demo with 4 simulated transactions...\n")
    for _ in range(4):
        amount = round(random.uniform(20, 5000), 2)
        txn_type = random.choice(["credit", "debit"])
        name = random.choice(DEMO_NAMES)
        txn = make_transaction(amount, txn_type, name, "", "")
        announce_transaction(txn, engine=engine, language=lang, play=play)
        time.sleep(0.5)
        print()


def parse_args():
    p = argparse.ArgumentParser(description="UPI Transaction Audio Notifier")
    p.add_argument("--amount", type=float, help="Transaction amount in INR")
    p.add_argument("--type", choices=["credit", "debit"], default="credit")
    p.add_argument("--name", default="Unknown", help="Name of the other party")
    p.add_argument("--vpa", default="", help="UPI VPA, e.g. name@okaxis")
    p.add_argument("--note", default="")
    p.add_argument("--engine", choices=["pyttsx3", "gtts"], default="pyttsx3")
    p.add_argument("--lang", choices=["en", "hi"], default="en")
    p.add_argument("--no-play", action="store_true")
    p.add_argument("--interactive", action="store_true")
    p.add_argument("--demo", action="store_true")

    # In Jupyter/Colab, sys.argv will contain elements like '-f' which argparse doesn't recognize.
    # We use parse_known_args to ignore these.
    args, unknown = p.parse_known_args()
    return args


def main():
    args = parse_args()
    play = not args.no_play

    if args.demo:
        run_demo(args.engine, args.lang, play)
    elif args.interactive:
        run_interactive(args.engine, args.lang, play)
    elif args.amount is not None:
        txn = make_transaction(args.amount, args.type, args.name, args.vpa, args.note)
        announce_transaction(txn, engine=args.engine, language=args.lang, play=play)
    else:
        # Modified to call run_demo if no specific arguments are provided for a quick demo
        print("No specific arguments provided. Running a demo.")
        run_demo(args.engine, args.lang, play)


if __name__ == "__main__":
    main()

