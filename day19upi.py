AUDIO_DIR = "static/audio"
CSV_PATH = "data/transactions.csv"
CSV_FIELDS = ["txn_id", "timestamp", "txn_type", "amount", "payer_name",
              "payee_name", "vpa", "note", "audio_file"]
DEMO_NAMES = ["Ramesh Kumar", "Priya Sharma", "Amit Traders", "Sneha Patel", "Kirana Store"]


# --------------------------------------------------------------------------- #
# Transaction model
# --------------------------------------------------------------------------- #
class TransactionType(str, Enum):
    CREDIT = "credit"   # money received
    DEBIT = "debit"     # money sent / paid


@dataclass
class UPITransaction:
    amount: float
    txn_type: TransactionType
    payer_name: str = "Unknown"
    payee_name: str = "Unknown"
    vpa: str = ""
    txn_id: str = field(default_factory=lambda: f"UPI{uuid.uuid4().hex[:12].upper()}")
    timestamp: datetime = field(default_factory=datetime.now)
    note: str = ""

    def __post_init__(self):
        if isinstance(self.txn_type, str):
            self.txn_type = TransactionType(self.txn_type.lower())
        if self.amount <= 0:
            raise ValueError("Transaction amount must be greater than zero")

    @property
    def counterparty(self) -> str:
        return self.payer_name if self.txn_type == TransactionType.CREDIT else self.payee_name

    def to_dict(self) -> dict:
        return {
            "txn_id": self.txn_id,
            "amount": self.amount,
            "txn_type": self.txn_type.value,
            "payer_name": self.payer_name,
            "payee_name": self.payee_name,
            "vpa": self.vpa,
            "timestamp": self.timestamp.isoformat(timespec="seconds"),
            "note": self.note,
        }


# --------------------------------------------------------------------------- #
# Message builder
# --------------------------------------------------------------------------- #
def _format_amount_words(amount: float) -> str:
    rupees = int(amount)
    paise = round((amount - rupees) * 100)
    if paise:
        return f"{rupees} rupees and {paise} paise"
    return f"{rupees} rupees"


def build_message(txn: UPITransaction, language: str = "en") -> str:
    amount_words = _format_amount_words(txn.amount)
    who = txn.counterparty

    if txn.txn_type == TransactionType.CREDIT:
        return (f"{amount_words} prapt hue, {who} se."
                if language == "hi" else f"Received {amount_words} from {who}.")
    return (f"{amount_words} bheje gaye, {who} ko."
            if language == "hi" else f"Paid {amount_words} to {who}.")


# --------------------------------------------------------------------------- #
# Text-to-speech
# --------------------------------------------------------------------------- #
class AudioGenerationError(Exception):
    pass


def generate_with_pyttsx3(text: str, out_path: str, rate: int = 165, volume: float = 1.0) -> str:
    import pyttsx3

    engine = pyttsx3.init()
    engine.setProperty("rate", rate)
    engine.setProperty("volume", volume)
    engine.save_to_file(text, out_path)
    engine.runAndWait()
    engine.stop()
    if not os.path.exists(out_path) or os.path.getsize(out_path) == 0:
        raise AudioGenerationError("pyttsx3 failed to write an audio file")
    return out_path


def generate_with_gtts(text: str, out_path: str, lang: str = "en") -> str:
    from gtts import gTTS

    tts = gTTS(text=text, lang=lang)
    tts.save(out_path)
    if not os.path.exists(out_path) or os.path.getsize(out_path) == 0:
        raise AudioGenerationError("gTTS failed to write an audio file")
    return out_path


def generate_audio(text: str, out_path: str, engine: str = "pyttsx3", lang: str = "en") -> str:
    if engine == "gtts":
        try:
            return generate_with_gtts(text, out_path, lang=lang)
        except Exception as exc:
            print(f"[audio] gTTS unavailable ({exc}); falling back to pyttsx3.")
            engine = "pyttsx3"

    if engine == "pyttsx3":
        base, _ext = os.path.splitext(out_path)
        wav_path = base + ".wav"
        return generate_with_pyttsx3(text, wav_path)

    raise ValueError(f"Unknown TTS engine: {engine}")


# --------------------------------------------------------------------------- #
# Playback
# --------------------------------------------------------------------------- #
def play_audio(path: str) -> bool:
    system = platform.system()
    try:
        if system == "Darwin":
            subprocess.run(["afplay", path], check=True)
            return True
        if system == "Windows":
            import winsound  # type: ignore
            winsound.PlaySound(path, winsound.SND_FILENAME)
            return True
        for player in ("paplay", "aplay", "ffplay", "mpg123"):
            if shutil.which(player):
                cmd = [player, path]
                if player == "ffplay":
                    cmd = ["ffplay", "-nodisp", "-autoexit", "-loglevel", "quiet", path]
                subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                return True
        print(f"[player] No audio player found. File saved at: {path}")
        return False
    except Exception as exc:
        print(f"[player] Could not play audio ({exc}). File saved at: {path}")
        return False


# --------------------------------------------------------------------------- #
# CSV ledger
# --------------------------------------------------------------------------- #
def log_transaction(txn: UPITransaction, audio_file: str, csv_path: str = CSV_PATH) -> None:
    os.makedirs(os.path.dirname(csv_path) or ".", exist_ok=True)
    file_exists = os.path.exists(csv_path)
    row = txn.to_dict()
    row["audio_file"] = audio_file
    with open(csv_path, "a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_FIELDS)
        if not file_exists:
            writer.writeheader()
        writer.writerow(row)


# --------------------------------------------------------------------------- #
# Orchestrator
# --------------------------------------------------------------------------- #
def announce_transaction(txn: UPITransaction, engine: str = "pyttsx3", language: str = "en",
                          play: bool = True, csv_path: str = CSV_PATH) -> str:
    os.makedirs(AUDIO_DIR, exist_ok=True)
    message = build_message(txn, language=language)
    out_path = os.path.join(AUDIO_DIR, f"{txn.txn_id}.mp3")
    audio_file = generate_audio(message, out_path, engine=engine, lang=language)

    print(f"[notifier] {txn.txn_type.value.upper()}  Rs {txn.amount:,.2f}  "
          f"({txn.counterparty})  ->  \"{message}\"")
    print(f"[notifier] audio saved: {audio_file}")

    if play:
        play_audio(audio_file)
    log_transaction(txn, audio_file, csv_path=csv_path)
    return audio_file


