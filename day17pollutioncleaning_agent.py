import random

class pollutiongrid:
    def __init__(self, rows=10, cols=10, pollution_ratio=0.15,
                 obstacle_ratio=0.08, seed=None, start=(0,0)):
        self.rows = rows
        self.cols = cols
        self.start = start
        if seed is not None:
            random.seed(seed)
        self.grid = [[0 for _ in range(cols)] for _ in range(rows)]
        self._populate(pollution_ratio, obstacle_ratio)
        # Corrected: Iterate through self.grid to count polluted cells
        self.total_polluted = sum(row.count(1) for row in self.grid)
        self.cleaned_count = 0

    def _populate(self, pollution_ratio, obstacle_ratio):
        cells = [(r,c) for r in range(self.rows) for c in range(self.cols) if (r,c) != self.start]
        random.shuffle(cells)
        n_obstacles = int(len(cells) * obstacle_ratio)
        n_pollution = int(len(cells) * pollution_ratio)
        obstacle_cells = cells[:n_obstacles]
        pollution_cells = cells[n_obstacles:n_obstacles+n_pollution]

        for (r,c) in obstacle_cells:
            self.grid[r][c] = -1
        for (r,c) in pollution_cells: # Corrected indentation
            self.grid[r][c] = 1

    def in_bounds(self, pos):
        r,c = pos
        return 0 <= r < self.rows and 0 <= c < self.cols

    def is_walkable(self, pos):
        r,c = pos
        return self.grid[r][c] != -1

    def is_polluted(self, pos):
        r,c = pos
        return self.grid[r][c] == 1

    def clean(self, pos):
        r,c = pos
        if self.grid[r][c] == 1:
            self.grid[r][c] = 0 # Corrected: Assignment operator
            self.cleaned_count += 1
            return True
        return False

    def polluted_cells(self):
        return [(r,c) for r in range(self.rows) for c in range(self.cols) if self.grid[r][c] == 1]

    def is_fully_clean(self):
        return self.cleaned_count >= self.total_polluted

    def neighbors(self, pos):
        r,c = pos
        candidates = [(r-1,c), (r+1,c), (r,c-1), (r,c+1)]
        return [p for p in candidates if self.in_bounds(p) and self.is_walkable(p)]

