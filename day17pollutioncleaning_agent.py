def bfs_path(env, start, goal):
    if start == goal:
        return [start]

    visited = {start}
    queue = deque([(start, [start])])

    while queue:
        current, path = queue.popleft()
        for nxt in env.neighbors(current): # Fixed: neighbours -> neighbors
            if nxt in visited:
                continue
            new_path = path + [nxt]
            if nxt == goal:
                return new_path
            visited.add(nxt)
            queue.append((nxt, new_path))

    return None

def astar_path(env, start, goal):
    def h(pos):
        return abs(pos[0] - goal[0]) + abs(pos[1] - goal[1])

    open_set = [(h(start), 0, start, [start])]
    best_cost = {start: 0}

    while open_set:
        _, cost, current, path = heapq.heappop(open_set)

        if current == goal:
            return path

        for nxt in env.neighbors(current): # Fixed: neighbours -> neighbors
            new_cost = cost + 1
            if nxt not in best_cost or new_cost < best_cost[nxt]:
                best_cost[nxt] = new_cost
                heapq.heappush(open_set, (new_cost + h(nxt), new_cost, nxt, path + [nxt]))

    return None

def find_nearest_polluted(env, start):
    if env.is_polluted(start):
        return start, [start]

    visited = {start}
    queue = deque([(start, [start])]) # Fixed: Deque -> deque

    while queue:
        current, path = queue.popleft()
        for nxt in env.neighbors(current):
            if nxt in visited:
                continue
            new_path = path + [nxt]
            if env.is_polluted(nxt):
                return nxt, new_path
            visited.add(nxt)
            queue.append((nxt, new_path))

    return None, None

class cleaningagent:
    def __init__(self, env, start=None):
        self.env = env
        self.pos = start if start is not None else env.start
        self.path_history = [self.pos]
        self.clean_events = []
        self.moves = 0

    def run(self, max_iterations=1000):
        iteration = 0
        while not self.env.is_fully_clean() and iteration < max_iterations: # Fixed: max_iteration -> max_iterations
            target, path = find_nearest_polluted(self.env, self.pos)
            if target is None:
                break

            for step in path[1:]:
                self.pos = step
                self.path_history.append(self.pos)
                self.moves += 1
                # Clean the cell after moving to it
                if self.env.is_polluted(self.pos):
                    self.env.clean(self.pos)
                    self.clean_events.append(len(self.path_history) - 1)

            iteration += 1
        return self.env.is_fully_clean()

